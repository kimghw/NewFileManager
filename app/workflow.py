_CATALOG = APP / "static" / "task_catalog.js"


def catalog():
    """task_catalog.js(화면의 원본)에서 ({job: {name, desc, accept}}, {묶음 meta: {no, name}}) — TASK 이름·한 줄 설명과 이관·취합의 「N단계 이름」."""
    text = _CATALOG.read_text(encoding="utf-8")
    heads = list(re.finditer(r'^  (\w+): \{ name: "([^"]*)"', text, re.M))
    tasks = {}
    for i, m in enumerate(heads):
        seg = text[m.end(): heads[i + 1].start() if i + 1 < len(heads) else len(text)]
        d = re.search(r'\bdesc: "([^"]*)"', seg)
        a = re.search(r"\baccept: \[([^\]]*)\]", seg)   # 그 TASK 의 카드가 받는 확장자(없으면 hwp·hwpx — task_catalog.js taskAcceptOf)
        tasks[m[1]] = {"name": m[2], "desc": d[1] if d else "", "accept": [x.strip(" \"'") for x in a[1].split(",") if x.strip()] if a else ["hwp", "hwpx"]}
    return tasks, {m[1]: {"no": m[2], "name": m[3]} for m in re.finditer(r'^  (\w+): \{ no: "([^"]*)", name: "([^"]*)"', text, re.M)}


