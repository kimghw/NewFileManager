def _groups(t):
    return t.get("stages") or ()


def steps():
    """등록부의 모든 단계 → [(어디: "task:<job>" | "common:<id>", 단계)] — 시험과 listing 이 같이 쓴다."""
    out = [(f"task:{t['job']}", s) for t in TASKS for g in _groups(t) for s in g["steps"]]
    return out + [(f"common:{c['id']}", s) for c in COMMON for s in c["steps"]]


def module_path(name):
    """모듈 이름 → 저장소 기준 경로(`app/<이름>.py` · 묶음이면 `app/<이름>/`) | None(없음)."""
    if (APP / f"{name}.py").is_file():
        return f"app/{name}.py"
    return f"app/{name}/" if (APP / name / "__init__.py").is_file() else None


_DOCS = {}


def _doc(name):
    """모듈 설명의 첫 줄(파일의 docstring) — 화면의 모듈 이름 옆 글. 못 읽으면 빈 글. 파일이 바뀌면 다시 읽는다."""
    path = module_path(name)
    if not path:
        return ""
    p = ROOT / path / "__init__.py" if path.endswith("/") else ROOT / path
    try:
        stamp = p.stat().st_mtime
        if _DOCS.get(name, (None, ""))[0] != stamp:
            _DOCS[name] = (stamp, ((ast.get_docstring(ast.parse(p.read_text(encoding="utf-8"))) or "").strip().splitlines() or [""])[0].strip()[:300])
        return _DOCS[name][1]
    except (OSError, SyntaxError, ValueError):
        return ""


