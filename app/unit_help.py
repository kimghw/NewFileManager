def only_kind(family, key):
    """(가족, 줄 key) → 전용의 종류 "rnd" | "relay" | "gather" | ""(문서를 가리지 않음) | None(이 표에 없는 줄) — `of` 와 같은 차례(가족의 것이 먼저 · 문서 하나는 제 줄만 · `hand1` … 은 `hand`)."""
    if isinstance(key, str) and key[:4] == "hand" and (key == "hand" or key[4:].isdigit()):
        return ""
    box = ONLY.get(family, {})
    if key in box:
        return box[key]
    return None if family == "single" else ONLY["common"].get(key)


